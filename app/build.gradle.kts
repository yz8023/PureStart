    alias(libs.plugins.kotlin.compose)
}

// Keep the existing manifest the source of truth. AGP 8 requires its package
// declaration to be expressed as namespace instead of in the source manifest.
val repo = rootProject.projectDir
val generated = layout.buildDirectory.dir("generated/purestart").get().asFile
val generatedManifest = generated.resolve("AndroidManifest.xml")
// v15.1.2: these files used to be written during configuration, so `clean` deleted
// them after configuration finished and the next manifest task failed with
// "mainManifest ... doesn't exist". They are now (re)generated by a task that the
// manifest-processing, Java-compile and resource tasks depend on.
val prepareGeneratedSources by tasks.registering {
    // Always re-run: clean removes the output directory, and BuildInfo carries a timestamp.
    outputs.upToDateWhen { false }
    // Declare only what this task writes: AGP also keeps baseline-prof.txt in the
    // same directory, and claiming the whole directory breaks task dependencies.
    outputs.file(generatedManifest)
    outputs.dir(generated.resolve("java"))
    outputs.dir(generated.resolve("resources"))
    doLast {
        generatedManifest.parentFile.mkdirs()
        generatedManifest.writeText(repo.resolve("AndroidManifest.xml").readText()
            .replace(Regex("\\s+package=\"com\\.yz8023\\.purestart\""), ""))
        val generatedJava = generated.resolve("java/com/yz8023/purestart/BuildInfo.java")
        generatedJava.parentFile.mkdirs()
        // Optional stable timestamp permits separate lint and R8 runs on low-memory hosts.
        val timeFormat = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm")
        val timestamp = System.getenv("PURESTART_BUILD_TIME")?.let {
            LocalDateTime.parse(it, timeFormat).format(timeFormat)
        } ?: LocalDateTime.now().format(timeFormat)
        generatedJava.writeText("package com.yz8023.purestart; public final class BuildInfo { public static final String BUILD_TIME = \"$timestamp\"; private BuildInfo() {} }")
        val xposed = generated.resolve("resources/META-INF/xposed")
        xposed.mkdirs()
        repo.resolve("xposed").listFiles()?.filter { it.isFile }?.forEach { it.copyTo(xposed.resolve(it.name), overwrite = true) }
        // Match build.sh: the packaged module version is derived from the manifest.
        val source = repo.resolve("AndroidManifest.xml").readText()
        val versionName = Regex("android:versionName=\"([^\"]+)\"").find(source)!!.groupValues[1]
        val versionCode = Regex("android:versionCode=\"([^\"]+)\"").find(source)!!.groupValues[1]
        val prop = xposed.resolve("module.prop")
        prop.writeText(prop.readText().replace(Regex("(?m)^version=.*$"), "version=v$versionName")
            .replace(Regex("(?m)^versionCode=.*$"), "versionCode=$versionCode"))
    }
}

// Everything that consumes the generated manifest / BuildInfo must wait for the task.
tasks.matching {
    it.name.startsWith("process") && it.name.contains("Manifest") ||
        it.name.startsWith("compile") && it.name.contains("JavaWithJavac") ||
        it.name.startsWith("javaPreCompile") ||
        it.name.startsWith("generate") && it.name.contains("Resources") ||
        it.name.startsWith("merge") && it.name.contains("Resources")
}.configureEach { dependsOn(prepareGeneratedSources) }

android {
    namespace = "com.yz8023.purestart"
    compileSdk = 36
    defaultConfig { applicationId = "com.yz8023.purestart"; minSdk = 26; targetSdk = 34 }
    sourceSets.getByName("main") {
        manifest.srcFile(generatedManifest)
        java.srcDirs(repo.resolve("src"), repo.resolve("compose-ui"), generated.resolve("java"))
        res.srcDirs(repo.resolve("res"))
        resources.srcDirs(generated.resolve("resources"))
    }
    compileOptions { sourceCompatibility = JavaVersion.VERSION_17; targetCompatibility = JavaVersion.VERSION_17 }
    buildFeatures { compose = true }
    // Follow build.sh: never silently generate a replacement release key.
    val releaseKeyPath = System.getenv("KEYSTORE_PATH")
    val configuredSigning = if (!releaseKeyPath.isNullOrBlank()) {
        signingConfigs.create("providedRelease") {
            storeFile = repo.resolve(releaseKeyPath)
            storePassword = System.getenv("KEYSTORE_PASS") ?: "android"
            keyAlias = System.getenv("KEY_ALIAS") ?: "androiddebugkey"
            keyPassword = System.getenv("KEY_PASS") ?: "android"
        }
    } else null
    buildTypes {
        getByName("release") {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = configuredSigning
        }
    }
    packaging { resources.excludes += "/META-INF/{AL2.0,LGPL2.1}" }
}
